#!/usr/bin/env python3
"""
VAPT Report Generator — structured markdown/PDF skeleton from findings JSON.
Reads nightly audit findings (JSONL) and produces a consolidated report with
executive summary, evidence tables, and CVSS v4 severity breakdowns.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from dataclasses import asdict
from datetime import datetime
from typing import Dict, List, Optional


SEVERITY_ORDER = ["critical", "high", "medium", "low", "informational"]
SEVERITY_COLORS = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🟢", "informational": "⚪"}


def load_findings(path: str) -> List[dict]:
    """Load a JSON or JSONL findings file."""
    results: List[dict] = []
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            content = fh.read().strip()
        if not content:
            return results
        # Try JSON first
        data = json.loads(content)
        if isinstance(data, list):
            results = data
        elif isinstance(data, dict):
            results = [data]
    except json.JSONDecodeError:
        # Fall back to JSONL
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    try:
                        results.append(json.loads(line))
                    except json.JSONDecodeError:
                        pass
    return results


def cvss_score_to_severity(score: Optional[float]) -> str:
    """Map a CVSS numeric score to severity band."""
    if score is None:
        return "informational"
    if score >= 9.0:
        return "critical"
    if score >= 7.0:
        return "high"
    if score >= 4.0:
        return "medium"
    if score > 0.0:
        return "low"
    return "informational"


def build_summary(findings: List[dict]) -> Dict:
    """Build executive summary statistics."""
    by_severity = Counter()
    by_category = Counter()
    by_cwe = Counter()
    scores: List[float] = []
    for f in findings:
        sev = (f.get("severity") or f.get("cvss_v4_severity") or "").lower()
        if sev in SEVERITY_ORDER:
            by_severity[sev] += 1
        cat = f.get("category", f.get("skill", "uncategorized"))
        by_category[cat] += 1
        cwe = f.get("cwe_id") or ""
        if cwe:
            by_cwe[cwe] += 1
        score = f.get("cvss_v4_base_score") or f.get("cvss_v31_score")
        if isinstance(score, (int, float)):
            scores.append(float(score))
    return {
        "total_findings": len(findings),
        "by_severity": dict(by_severity),
        "top_categories": dict(by_category.most_common(10)),
        "unique CWEs": len(by_cwe),
        "avg_cvss": round(sum(scores) / len(scores), 2) if scores else None,
        "max_cvss": round(max(scores), 2) if scores else None,
    }


def generate_markdown(target: str, findings: List[dict], summary: dict, output_path: str) -> None:
    """Write a consolidated VAPT report in Markdown format."""
    lines: List[str] = []
    ts = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    lines.append(f"# Vulnerability Assessment Report")
    lines.append(f"")
    lines.append(f"- **Target:** {target}")
    lines.append(f"- **Date:** {ts}")
    lines.append(f"- **Report generated by:** NIGHTFANG v1 automation")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")
    lines.append(f"## Executive Summary")
    lines.append(f"")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Total Findings | {summary['total_findings']} |")
    lines.append(f"| Critical | {summary['by_severity'].get('critical', 0)} |")
    lines.append(f"| High | {summary['by_severity'].get('high', 0)} |")
    lines.append(f"| Medium | {summary['by_severity'].get('medium', 0)} |")
    lines.append(f"| Low | {summary['by_severity'].get('low', 0)} |")
    lines.append(f"| Informational | {summary['by_severity'].get('informational', 0)} |")
    if summary["avg_cvss"] is not None:
        lines.append(f"| Avg CVSS Score | {summary['avg_cvss']} |")
    if summary["max_cvss"] is not None:
        lines.append(f"| Max CVSS Score | {summary['max_cvss']} |")
    lines.append(f"")
    lines.append(f"## Top Categories")
    lines.append(f"")
    for cat, count in summary["top_categories"].items():
        lines.append(f"- **{cat}**: {count} finding(s)")
    lines.append(f"")
    lines.append(f"## Detailed Findings")
    lines.append(f"")

    sorted_findings = sorted(findings, key=lambda f: (
        SEVERITY_ORDER.index(f.get("severity", "informational").lower())
        if f.get("severity", "").lower() in SEVERITY_ORDER else 9
    ))

    for idx, f in enumerate(sorted_findings, start=1):
        sev = (f.get("severity") or "informational").lower()
        color = SEVERITY_COLORS.get(sev, "⚪")
        title = f.get("title") or f.get("finding_title") or f"Finding #{idx}"
        desc = f.get("description") or f.get("detail") or ""
        evidence = f.get("evidence") or f.get("proof") or ""
        remediation = f.get("remediation") or f.get("fix") or ""
        cwe = f.get("cwe_id") or ""
        cvss = f.get("cvss_v4_base_score") or f.get("cvss_v31_score")
        conf = f.get("confidence") or ""

        lines.append(f"### {color} {idx}. {title}")
        lines.append(f"")
        lines.append(f"**Severity:** {sev.upper()}  ")
        lines.append(f"**Confidence:** {conf or 'Unrated'}")
        if cwe:
            lines.append(f"**CWE:** [{cwe}](https://cwe.mitre.org/data/definitions/{cwe.replace('CWE-', '')}.html)")
        if cvss is not None:
            lines.append(f"**CVSS v4 Base Score:** {cvss}")
        lines.append(f"")
        if desc:
            lines.append(f"**Description:**\n{desc}")
            lines.append(f"")
        if evidence:
            lines.append(f"**Evidence:**\n```json\n{evidence[:1500]}\n```")
            lines.append(f"")
        if remediation:
            lines.append(f"**Remediation:**\n{remediation}")
            lines.append(f"")
        lines.append(f"---")
        lines.append(f"")

    lines.append(f"*Report generated by NIGHTFANG on {ts}*")
    lines.append(f"")

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(
        description="NIGHTFANG VAPT Consolidated Report Generator",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("input", help="Path to findings JSON or JSONL file")
    parser.add_argument("-o", "--output", metavar="PATH", required=True, help="Output Markdown report path")
    parser.add_argument("--target", metavar="NAME", help="Target name for report header")
    args = parser.parse_args()

    target = args.target or os.path.basename(args.input).split(".")[0]
    findings = load_findings(args.input)
    if not findings:
        print("[!] No findings loaded from input.", file=sys.stderr)
        return 2

    summary = build_summary(findings)
    output_path = args.output
    generate_markdown(target, findings, summary, output_path)
    print(f"\n  [*] Generated report: {output_path}")
    print(f"      Findings: {summary['total_findings']}  |  "
          f"Critical: {summary['by_severity'].get('critical', 0)}  |  "
          f"High: {summary['by_severity'].get('high', 0)}  |  "
          f"Avg CVSS: {summary.get('avg_cvss') or 'N/A'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
